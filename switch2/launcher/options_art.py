# The options screen, drawn ahead of time: a background (header, title, row labels, footer) and the
# pieces the port lays over it for the current state. Writes port/switch2/options_art.h.
# Usage: python3 options_art.py <version> [melee-unlocked checkout]
import os, sys, zlib, numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont
HERE=os.path.dirname(os.path.abspath(__file__)); VER=sys.argv[1] if len(sys.argv)>1 else '0.0.0'
MU=sys.argv[2] if len(sys.argv)>2 else '/home/claude/src/mu'
K=3; W,H=1280,720; G=os.environ.get('POPPINS_DIR','/usr/share/fonts/truetype/google-fonts')+'/'
def F(n,s): return ImageFont.truetype(G+'Poppins-%s.ttf'%n,int(s*K))
BG=(51,51,51); CY=(125,228,247); WH=(255,255,255); DIM=(150,150,150)
ROWS=['Rumble','Tap jump','Scale','Logging','Custom textures']
VALUES=['On','Off','1x','1.5x','2x','3x','4x']
DESC=['Controller rumble. Melee’s own per-player Rumble option also applies.',
      'On: pushing the stick up jumps, as in the original game. Off: only X and Y jump.',
      'Internal resolution. Every setting holds 60 fps in matches; at 4x, 3-4 player results screens dip.',
      'Writes boot.log and gl.log to sdmc:/melee/, for reporting a problem.',
      'Dolphin-format texture packs (downloaded separately), each in its own folder in sdmc:/melee/textures/.']
Y0,DY,LABEL_RX,VALUE_CX=212,64,600,790; DESC_Y=550
def canvas(): return Image.new('RGBA',(W*K,H*K),(0,0,0,0))
def key(d,x,y,kk,label,f=None):
    f=f or F('Light',20)
    d.ellipse([x*K,y*K,(x+34)*K,(y+34)*K],outline=CY+(255,),width=2*K)
    cx,cy=(x+17)*K,(y+17)*K; t=5*K
    if kk=='UD':   # up and down triangles
        d.polygon([(cx,cy-9*K),(cx-t,cy-2*K),(cx+t,cy-2*K)],fill=CY+(255,)); d.polygon([(cx,cy+9*K),(cx-t,cy+2*K),(cx+t,cy+2*K)],fill=CY+(255,))
    elif kk=='LR':
        d.polygon([(cx-9*K,cy),(cx-2*K,cy-t),(cx-2*K,cy+t)],fill=CY+(255,)); d.polygon([(cx+9*K,cy),(cx+2*K,cy-t),(cx+2*K,cy+t)],fill=CY+(255,))
    else: d.text((cx,cy),kk,font=F('Medium',20),fill=CY+(255,),anchor='mm')
    d.text(((x+46)*K,(y+17)*K),label,font=f,fill=WH+(255,),anchor='lm'); return x+46+d.textlength(label,font=f)/K+40
# background
bg=Image.new('RGBA',(W*K,H*K),BG+(255,)); d=ImageDraw.Draw(bg)
t='MELEE'; f=F('Light',22); f2=F('Medium',22); tw=d.textlength(t,font=f)/K
d.text((26*K,34*K),t,font=f,fill=WH+(255,),anchor='lm'); d.text(((26+tw+8)*K,34*K),'SWITCH 2 PORT',font=f2,fill=CY+(255,),anchor='lm')
d.text(((W-26)*K,34*K),'v'+VER+'  ·  Prlxd',font=F('Light',16),fill=(200,200,200,255),anchor='rm')
d.text((W/2*K,128*K),'Options',font=F('Light',44),fill=WH+(255,),anchor='mm')
for i,r in enumerate(ROWS):
    d.text((LABEL_RX*K,(Y0+i*DY)*K),r,font=F('Light',28),fill=DIM+(255,),anchor='rm')
fk=F('Light',20); items=[('UD','Choose'),('LR','Change'),('B','Back')]
x=(W-(sum(46+d.textlength(l,font=fk)/K+40 for _,l in items)-40))/2
for kk,l in items: x=key(d,x,628,kk,l)
d.text((W/2*K,690*K),'Saved to sdmc:/melee/config.ini as you change it.',font=F('Light',16),fill=(170,170,170,255),anchor='mm')
bg=bg.resize((W,H),Image.LANCZOS).convert('RGB')
def sprite(draw_fn,w,h):
    im=Image.new('RGBA',(w*K,h*K),(0,0,0,0)); draw_fn(ImageDraw.Draw(im),w,h); return im.resize((w,h),Image.LANCZOS)
sprites=[]
def add(name,im): sprites.append((name,im))
# the selected row's band: a slightly lighter strip with a cyan bar at its left end
def band(d,w,h):
    d.rounded_rectangle([0,0,w*K-1,h*K-1],radius=10*K,fill=(255,255,255,18)); d.rectangle([0,6*K,5*K,(h-6)*K],fill=CY+(255,))
add('band',sprite(band,640,58))
for i,r in enumerate(ROWS):
    def lab(d,w,h,r=r): d.text((w*K,h/2*K),r,font=F('Light',28),fill=WH+(255,),anchor='rm')
    add('label%d'%i,sprite(lab,260,50))
for j,v in enumerate(VALUES):
    def val(d,w,h,v=v,sel=False): d.text((w/2*K,h/2*K),v,font=F('Medium' if sel else 'Light',28),fill=(CY if sel else (200,200,200))+(255,),anchor='mm')
    def vals(d,w,h,v=v):
        d.text((w/2*K,h/2*K),v,font=F('Medium',28),fill=CY+(255,),anchor='mm')
        d.text((20*K,h/2*K),'‹',font=F('Medium',30),fill=CY+(255,),anchor='mm'); d.text(((w-20)*K,h/2*K),'›',font=F('Medium',30),fill=CY+(255,),anchor='mm')
    add('value%d'%j,sprite(val,200,50)); add('valuesel%d'%j,sprite(vals,200,50))
for i,t in enumerate(DESC):
    def desc(d,w,h,t=t): d.text((w/2*K,h/2*K),t,font=F('Light',19),fill=(215,215,215,255),anchor='mm')
    add('desc%d'%i,sprite(desc,1100,40))
out=['// Generated by launcher/options_art.py: the options screen. Background RGB 1280x720; sprites RGBA.\n',
     '#include <cstdint>\n#include <cstddef>\n',
     'static const int opt_y0 = %d, opt_dy = %d, opt_label_rx = %d, opt_value_cx = %d, opt_desc_y = %d;\n'%(Y0,DY,LABEL_RX,VALUE_CX,DESC_Y),
     'static const int opt_rows = %d, opt_values = %d;\n'%(len(ROWS),len(VALUES))]
z=zlib.compress(bg.tobytes(),9); out.append('static const uint8_t opt_bg[] = {%s};\n'%','.join(map(str,z)))
out.append('struct OptSprite { const uint8_t* data; size_t size; int w, h; };\n')
for name,im in sprites:
    z=zlib.compress(im.tobytes(),9); out.append('static const uint8_t optpx_%s[] = {%s};\n'%(name,','.join(map(str,z))))
def ref(n): im=dict(sprites)[n]; return '{optpx_%s, sizeof optpx_%s, %d, %d}'%(n,n,im.width,im.height)
out.append('static const OptSprite opt_band = %s;\n'%ref('band'))
out.append('static const OptSprite opt_label[%d] = {%s};\n'%(len(ROWS),','.join(ref('label%d'%i) for i in range(len(ROWS)))))
out.append('static const OptSprite opt_value[%d] = {%s};\n'%(len(VALUES),','.join(ref('value%d'%i) for i in range(len(VALUES)))))
out.append('static const OptSprite opt_value_sel[%d] = {%s};\n'%(len(VALUES),','.join(ref('valuesel%d'%i) for i in range(len(VALUES)))))
out.append('static const OptSprite opt_desc[%d] = {%s};\n'%(len(ROWS),','.join(ref('desc%d'%i) for i in range(len(ROWS)))))
open(os.path.join(MU,'port','switch2','options_art.h'),'w').write(''.join(out))
# a preview: row 2 (Scale) selected at 2x, the rest at their defaults
pv=bg.convert('RGBA'); S=dict(sprites); state=[1,0,4,1,1]; sel=2
def paste(im,x,y): pv.alpha_composite(im,(int(x),int(y)))
paste(S['band'],LABEL_RX-320,Y0+sel*DY-29)
for i in range(len(ROWS)):
    y=Y0+i*DY
    if i==sel: paste(S['label%d'%i],LABEL_RX-260,y-25)
    v=S[('valuesel%d' if i==sel else 'value%d')%state[i]]; paste(v,VALUE_CX-100,y-25)
paste(S['desc%d'%sel],W/2-550,DESC_Y-20)
pv.convert('RGB').save(os.path.join(HERE,'options_preview.png'))
print(os.path.getsize(os.path.join(MU,'port','switch2','options_art.h')))
