# Slippi's menu files for the Slippi option, from melee-unlocked's port/slippi_sys (copied there from
# Slippi's Ishiiruka repository, GPL-2.0): VCDIFF patches applied to the disc's own menus at boot,
# and slpCSS.dat as is. Packed (zlib) into slippi_sys_files.h.
import sys, zlib, os
# Usage: python3 slippi_sys.py <melee-unlocked checkout>
MU = sys.argv[1] if len(sys.argv) > 1 else '.'
SRC = os.path.join(MU, 'port', 'slippi_sys', 'GameFiles', 'GALE01')
OUT = os.path.join(MU, 'port', 'switch2', 'slippi_sys_files.h')
NAMES = ['MnMaAll.usd', 'MnMaAll.dat', 'SdMenu.usd', 'SdMenu.dat', 'MnSlMap.usd', 'MnSlMap.dat',
         'SdSlChr.usd', 'SdSlChr.dat', 'MnExtAll.usd', 'MnExtAll.dat', 'slpCSS.dat', 'SlippiCSS_gui.dat']
out = ['// Generated by launcher/slippi_sys.py from Slippi\'s GameFiles (GPL-2.0). Each entry is a disc\n'
       '// file name, whether the data is a VCDIFF patch of the disc\'s own copy, and the zlib-packed data.\n'
       '#include <cstdint>\n#include <cstddef>\n']
rows = []; total = 0
for i, n in enumerate(NAMES):
    diff = os.path.exists(os.path.join(SRC, n + '.diff'))
    raw = open(os.path.join(SRC, n + ('.diff' if diff else '')), 'rb').read()
    z = zlib.compress(raw, 9); total += len(z)
    out.append('static const uint8_t slippi_sys_%d[] = {%s};\n' % (i, ','.join(map(str, z))))
    rows.append('{"%s", %s, slippi_sys_%d, sizeof slippi_sys_%d, %d}' % (n, 'true' if diff else 'false', i, i, len(raw)))
out.append('struct SlippiSysFile { const char* name; bool diff; const uint8_t* data; size_t size; size_t raw_size; };\n')
out.append('static const SlippiSysFile slippi_sys_files[] = {\n  %s};\n' % ',\n  '.join(rows))
open(OUT, 'w').write(''.join(out)); print(total)
