# Draws the "Preparing graphics" screen shown while shaders are built at launch, and writes
# port/switch2/prewarm_art.h: the screen as zlib-packed RGBA 1280x720, and where the progress bar's
# fill goes. Usage: python3 prewarm_screen.py <version> [melee-unlocked checkout]
import os, sys, zlib
from PIL import Image, ImageDraw, ImageFont, ImageFilter
HERE=os.path.dirname(os.path.abspath(__file__)); MU=sys.argv[2] if len(sys.argv)>2 else '.'
VER=sys.argv[1] if len(sys.argv)>1 else '0.0.0'
K=3; W,H=1280,720
G=os.environ.get('POPPINS_DIR','/usr/share/fonts/truetype/google-fonts')+'/'
def F(n,s): return ImageFont.truetype(G+'Poppins-%s.ttf'%n,int(s*K))
BG=(51,51,51); CY=(125,228,247); WH=(255,255,255); DIM=(170,170,170)
def background(mode):
    # The picked game's colours from the picker (launcher/make.py): a dark vertical gradient in the
    # panel's colour and a soft glow behind the title. 0 Melee (purple), 1 20XX (teal), 2 Slippi (green).
    top,bot,glow=(((62,26,78),(24,14,30),(150,70,170)),
                  ((22,52,62),(20,24,27),(70,150,165)),
                  ((22,62,42),(20,26,23),(70,190,120)))[mode]
    g=Image.new('RGB',(1,H))
    for y in range(H):
        t=y/H; g.putpixel((0,y),tuple(int(top[c]+(bot[c]-top[c])*t) for c in range(3)))
    bg=g.resize((W,H))
    m=Image.new('L',(W,H),0); ImageDraw.Draw(m).ellipse([W/2-330,300-90,W/2+330,300+90],fill=255)
    m=m.filter(ImageFilter.GaussianBlur(70)).point(lambda v:int(v*0.35))
    bg=Image.composite(Image.new('RGB',(W,H),glow),bg,m)
    return bg.resize((W*K,H*K),Image.BICUBIC).convert('RGBA')
NAMES=('Super Smash Bros. Melee','20XX Tournament Edition','Slippi Online')
def screen(title,line1,line2,preview,mode=0):
    global d
    im=background(mode); d=ImageDraw.Draw(im)
    def text(x,y,t,f,c,a='mm'): d.text((x*K,y*K),t,font=f,fill=c+(255,),anchor=a)
    f1,f2=F('Light',34),F('Medium',34); t1,t2='MELEE','SWITCH 2 PORT'
    w1,w2=d.textlength(t1,font=f1)/K,d.textlength(t2,font=f2)/K; x=(W-(w1+12+w2))/2
    text(x,48,t1,f1,WH,'lm'); text(x+w1+12,48,t2,f2,CY,'lm')
    text(W/2,92,NAMES[mode],F('Light',20),(215,215,215))
    text(W/2,300,title,F('Light',40),WH)
    d.rounded_rectangle([BX0*K-3*K,BY0*K-3*K,BX1*K+3*K,BY1*K+3*K],radius=9*K,outline=CY+(255,),width=2*K)
    text(W/2,440,line1,F('Light',20),DIM)
    if line2: text(W/2,470,line2,F('Light',20),DIM)
    text(W-26,690,'v'+VER+'  \u00b7  Prlxd',F('Light',16),(200,200,200),'rm')
    im=im.resize((W,H),Image.LANCZOS)
    BW,BH=BX1-BX0,BY1-BY0
    strip=im.crop((BX0,BY0,BX1,BY1)).resize((BW*K,BH*K)); sd=ImageDraw.Draw(strip)
    sd.rounded_rectangle([0,0,BW*K-1,BH*K-1],radius=BH*K//2,fill=CY+(255,))
    strip=strip.resize((BW,BH),Image.LANCZOS)
    full=Image.new('RGBA',(W,H+BH),(0,0,0,255)); full.paste(im,(0,0)); full.paste(strip,(0,H))
    pv=im.copy(); pv.paste(strip.crop((0,0,int(BW*0.6)-BH//2,BH)),(BX0,BY0)); pv.paste(strip.crop((BW-BH//2,0,BW,BH)),(BX0+int(BW*0.6)-BH//2,BY0))
    os.makedirs(os.path.join(HERE,'preview'),exist_ok=True); pv.convert('RGB').save(os.path.join(HERE,'preview',preview))
    return zlib.compress(full.tobytes(),9)
BX0,BY0,BX1,BY1=340,372,940,384           # the bar; its fill is drawn by the port
BH=BY1-BY0
Z=[];Z2=[]
for m in range(3):
    Z.append(screen('Preparing graphics','The first launch builds every shader once. This takes a minute or two.','Later launches are much quicker.','prewarm_preview_%d.png'%m,m))
    Z2.append(screen('Loading graphics','Loading the shaders built on an earlier launch: a few seconds.','','prewarm_again_preview_%d.png'%m,m))
H_=720
out=['// Generated by launcher/prewarm_screen.py: the "Preparing graphics" screen for each game of the\n// picker (0 Melee, 1 20XX, 2 Slippi), zlib-packed RGBA 1280x%d.\n'%(H_+BH),
     '#include <cstdint>\n#include <cstddef>\n',
     'static const int prewarm_bar[4] = {%d, %d, %d, %d};   // x0, y0, x1, y1 of the fill, top-left origin\n'%(BX0,BY0,BX1,BY1),
     'static const int prewarm_rows = %d;   // the screen (720 rows), then the filled bar (from row 720, x 0..)\n'%(H_+BH)]
for m in range(3):
    out.append('static const uint8_t prewarm_art_%d[] = {%s};\n'%(m,','.join(map(str,Z[m]))))
    out.append('static const uint8_t prewarm_art_again_%d[] = {%s};\n'%(m,','.join(map(str,Z2[m]))))
out.append('struct PrewarmArt { const uint8_t* data; size_t size; };\n')
out.append('static const PrewarmArt prewarm_art[3] = {%s};\n'%','.join('{prewarm_art_%d, sizeof prewarm_art_%d}'%(m,m) for m in range(3)))
out.append('// later launches at a resolution already played: "Loading graphics"\n')
out.append('static const PrewarmArt prewarm_art_again[3] = {%s};\n'%','.join('{prewarm_art_again_%d, sizeof prewarm_art_again_%d}'%(m,m) for m in range(3)))
open(os.path.join(MU,'port','switch2','prewarm_art.h'),'w').write(''.join(out)); print([len(z) for z in Z+Z2])
