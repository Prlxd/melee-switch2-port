# Draws the "Preparing graphics" screen shown while shaders are built at launch, and writes
# port/switch2/prewarm_art.h: the screen as zlib-packed RGBA 1280x720, and where the progress bar's
# fill goes. Usage: python3 prewarm_screen.py <version> [melee-unlocked checkout]
import os, sys, zlib
from PIL import Image, ImageDraw, ImageFont
HERE=os.path.dirname(os.path.abspath(__file__)); os.makedirs(os.path.join(HERE,'preview'),exist_ok=True); MU=sys.argv[2] if len(sys.argv)>2 else '.'
VER=sys.argv[1] if len(sys.argv)>1 else '0.0.0'
K=3; W,H=1280,720
G=os.environ.get('POPPINS_DIR','/usr/share/fonts/truetype/google-fonts')+'/'
def F(n,s): return ImageFont.truetype(G+'Poppins-%s.ttf'%n,int(s*K))
BG=(51,51,51); CY=(125,228,247); WH=(255,255,255); DIM=(170,170,170)
def screen(title,line1,line2,preview):
    global d
    im=Image.new('RGBA',(W*K,H*K),BG+(255,)); d=ImageDraw.Draw(im)
    def text(x,y,t,f,c,a='mm'): d.text((x*K,y*K),t,font=f,fill=c+(255,),anchor=a)
    f1,f2=F('Light',34),F('Medium',34); t1,t2='MELEE','SWITCH 2 PORT'
    w1,w2=d.textlength(t1,font=f1)/K,d.textlength(t2,font=f2)/K; x=(W-(w1+12+w2))/2
    text(x,48,t1,f1,WH,'lm'); text(x+w1+12,48,t2,f2,CY,'lm')
    text(W/2,300,title,F('Light',40),WH)
    d.rounded_rectangle([BX0*K-3*K,BY0*K-3*K,BX1*K+3*K,BY1*K+3*K],radius=9*K,outline=CY+(255,),width=2*K)
    text(W/2,440,line1,F('Light',20),DIM)
    if line2: text(W/2,470,line2,F('Light',20),DIM)
    text(W-26,690,'v'+VER+'  \u00b7  Prlxd',F('Light',16),(200,200,200),'rm')
    im=im.resize((W,H),Image.LANCZOS)
    BW,BH=BX1-BX0,BY1-BY0
    strip=im.crop((BX0,BY0,BX1,BY1)).resize((BW*K,BH*K)); sd=ImageDraw.Draw(strip)
    sd.rounded_rectangle([0,0,BW*K-1,BH*K-1],radius=BH*K//2,fill=CY+(255,))
    strip=strip.resize((BW,BH),Image.LANCZOS)
    full=Image.new('RGBA',(W,H+BH),BG+(255,)); full.paste(im,(0,0)); full.paste(strip,(0,H))
    pv=im.copy(); pv.paste(strip.crop((0,0,int(BW*0.6)-BH//2,BH)),(BX0,BY0)); pv.paste(strip.crop((BW-BH//2,0,BW,BH)),(BX0+int(BW*0.6)-BH//2,BY0))
    pv.convert('RGB').save(os.path.join(HERE,'preview',preview))
    return zlib.compress(full.tobytes(),9)
BX0,BY0,BX1,BY1=340,372,940,384           # the bar; its fill is drawn by the port
BH=BY1-BY0
z=screen('Preparing graphics','The first launch builds every shader once. This takes a minute or two.','Later launches are much quicker.','prewarm_preview.png')
z2=screen('Loading graphics','Loading the shaders built on an earlier launch: a few seconds.','','prewarm_again_preview.png')
H_=720
out=['// Generated by launcher/prewarm_screen.py: the "Preparing graphics" screen, zlib-packed RGBA 1280x%d.\n'%(H_+BH),
     '#include <cstdint>\n#include <cstddef>\n',
     'static const int prewarm_bar[4] = {%d, %d, %d, %d};   // x0, y0, x1, y1 of the fill, top-left origin\n'%(BX0,BY0,BX1,BY1),
     'static const int prewarm_rows = %d;   // the screen (720 rows), then the filled bar (from row 720, x 0..)\n'%(H_+BH),
     'static const uint8_t prewarm_art[] = {%s};\n'%','.join(map(str,z)),
     '// later launches at a resolution already played: "Loading graphics"\n',
     'static const uint8_t prewarm_art_again[] = {%s};\n'%','.join(map(str,z2))]
open(os.path.join(MU,'port','switch2','prewarm_art.h'),'w').write(''.join(out)); print(len(z))
