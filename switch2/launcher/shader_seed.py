# Packs one or more recipes.bin files (from sdmc:/melee/shader-cache/*/) into port/switch2/shader_seed.h,
# the shader list built into the NRO. No files: an empty seed.
# Usage: python3 shader_seed.py <melee-unlocked checkout> [recipes.bin ...]
import os, sys, zlib, struct, hashlib
MU=sys.argv[1]; files=sys.argv[2:]
MAGIC=0x3150524C47505847
recs=[]; seen=set(); size=None
for p in files:
    data=open(p,'rb').read()
    magic,count,_=struct.unpack_from('<QQQ',data,0)
    assert magic==MAGIC, p
    rs=(len(data)-24)//count if count else 0
    assert size in (None,rs), 'recipe size differs'
    size=rs
    for i in range(count):
        r=data[24+i*rs:24+(i+1)*rs]
        h=hashlib.sha1(r).digest()
        if h not in seen: seen.add(h); recs.append(r)
raw=b''.join(recs); z=zlib.compress(raw,9) if raw else b''
out=['// Generated by launcher/shader_seed.py: %d program recipes recorded on a Switch 2, zlib-packed.\n'%len(recs),
     '#include <cstdint>\n#include <cstddef>\n',
     'static const size_t shader_seed_count = %d, shader_seed_recipe_bytes = %d, shader_seed_raw_bytes = %d;\n'%(len(recs),size or 0,len(raw)),
     'static const uint8_t shader_seed[] = {%s};\n'%(','.join(map(str,z)) if z else '0')]
open(os.path.join(MU,'port','switch2','shader_seed.h'),'w').write(''.join(out)); print(len(recs),'recipes',len(z),'bytes packed')
